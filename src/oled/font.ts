/** A filled box: what a character the font doesn't have comes out as. */
const MISSING = [0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f];

/**
 * Five columns for a character, bit 0 the top row (the way GFX stores its font): column i of
 * `glyph(c)` lights row j when bit j is set.
 */
const COLS: number[][] = ROWS.map((line) => {
  const rows = line.split(' ').map((r) => parseInt(r, 2));
  return [0, 1, 2, 3, 4].map((i) => rows.reduce((col, row, j) => col | (((row >> (4 - i)) & 1) << j), 0));
});
const MISSING_COLS = [0, 1, 2, 3, 4].map((i) => MISSING.reduce((col, row, j) => col | (((row >> (4 - i)) & 1) << j), 0));

export function glyph(code: number): number[] {
  return code >= 32 && code <= 126 ? COLS[code - 32]! : MISSING_COLS;
}

/** True for characters the built-in font can draw. */
export const printable = (s: string) => [...s].every((ch) => ch.charCodeAt(0) >= 32 && ch.charCodeAt(0) <= 126);
