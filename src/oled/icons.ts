export const ICONS = Object.keys(ART) as IconId[];
export const ICON_NAME: Record<IconId, string> = { heart: 'Heart', smile: 'Smiley', thermo: 'Thermometer', wifi: 'Wi-Fi' };

/** Rows of bytes, MSB leftmost: what `drawBitmap` reads. */
export function iconBytes(id: IconId): number[] {
  return ART[id].flatMap((row) => [0, 8].map((o) => parseInt(row.slice(o, o + 8).replace(/#/g, '1').replace(/\./g, '0'), 2)));
}
